/**
 * Computes world coordinates of a pin taking component translation & rotation into account.
 */
export function getPinWorldPosition(
  compX: number,
  compY: number,
  pin: PinDefinition,
  rotation: 0 | 90 | 180 | 270
): { x: number; y: number } {
  let rotatedX = pin.x;
  let rotatedY = pin.y;

  if (rotation === 90) {
    rotatedX = -pin.y;
    rotatedY = pin.x;
  } else if (rotation === 180) {
    rotatedX = -pin.x;
    rotatedY = -pin.y;
  } else if (rotation === 270) {
    rotatedX = pin.y;
    rotatedY = -pin.x;
  }

  return {
    x: Math.round(compX + rotatedX),
    y: Math.round(compY + rotatedY),
  };
}
